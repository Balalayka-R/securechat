export default function EmojiPicker({ onSelect, onClose }) {
  const [category, setCategory] = useState('recent')
  const [recent, setRecent] = useState(EMOJI_CATEGORIES.recent)

  const handleSelect = (emoji) => {
    onSelect(emoji)
    // Add to recent
    if (!recent.includes(emoji)) {
      setRecent([emoji, ...recent.slice(0, 9)])
    }
  }

  const categories = [
    { key: 'recent', label: 'Недавние', icon: '⏱️' },
    { key: 'smileys', label: 'Смайлы', icon: '😀' },
    { key: 'gestures', label: 'Жесты', icon: '👋' },
    { key: 'hearts', label: 'Символы', icon: '❤️' },
    { key: 'other', label: 'Другое', icon: '🎉' },
  ]

  const emojis = category === 'recent' ? recent : EMOJI_CATEGORIES[category]

  return (
    <div className="bg-dark-800 rounded-xl border border-dark-700 shadow-xl p-2 w-[280px] sm:w-[320px]">
      {/* Header */}
      <div className="flex items-center justify-between mb-2 px-1">
        <span className="text-xs text-dark-400 font-medium">Эмодзи</span>
        <button 
          onClick={onClose}
          className="p-1 hover:bg-dark-700 rounded transition-colors"
        >
          <X className="w-4 h-4 text-dark-500" />
        </button>
      </div>

      {/* Emoji grid */}
      <div className="grid grid-cols-7 gap-1 p-1 max-h-[200px] overflow-y-auto">
        {emojis.map((emoji, i) => (
          <button
            key={`${emoji}-${i}`}
            onClick={() => handleSelect(emoji)}
            className="p-1.5 hover:bg-dark-700 rounded-lg text-xl transition-colors"
          >
            {emoji}
          </button>
        ))}
      </div>

      {/* Categories */}
      <div className="flex items-center justify-center gap-1 mt-2 pt-2 border-t border-dark-700">
        {categories.map(({ key, icon }) => (
          <button
            key={key}
            onClick={() => setCategory(key)}
            className={clsx(
              'p-2 rounded-lg text-lg transition-colors',
              category === key 
                ? 'bg-accent/20 text-accent' 
                : 'hover:bg-dark-700 text-dark-400'
            )}
          >
            {icon}
          </button>
        ))}
      </div>
    </div>
  )
}
